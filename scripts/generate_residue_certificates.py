from pathlib import Path
import sys,sympy as s
R=Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'scripts'))
from explicit_section_data import k,m,b,c,d,e,g
x=k
base=dict(zip(['bPoly','cPoly','dPoly','ePoly','gPoly'],[b,c,d,e,g]))
def poly(e):
 terms=[]
 for (n,),v in s.Poly(e,k).terms():
  q=s.Rational(v);co=f'C ({q.p}/{q.q} : ℚ)'
  terms.append(co+(f'*X^{n}' if n else ''))
 return ' + '.join(terms) if terms else '0'
w=[3*b*g-2*c*e,6*g+b*e-4*c*d,4*e-b*d-6*c,2*d-3*b]
u=[c*w[0]-6,b*w[0]+c*w[1],w[0]+b*w[1]+c*w[2],w[1]+b*w[2]+c*k]
names=['w0','w1','w2','w3','u0','u1','u2','u3','disc']
raws=w+u+[b*b-4*c]
exprs=['3*bPoly*gPoly-2*cPoly*ePoly','6*gPoly+bPoly*ePoly-4*cPoly*dPoly','4*ePoly-bPoly*dPoly-6*cPoly','2*dPoly-3*bPoly','cPoly*w0Poly-6','bPoly*w0Poly+cPoly*w1Poly','w0Poly+bPoly*w1Poly+cPoly*w2Poly','w1Poly+bPoly*w2Poly+cPoly*X','bPoly^2-4*cPoly']
scalar=['3*ExplicitCurve.sb k*ExplicitCurve.sg k-2*ExplicitCurve.sc k*ExplicitCurve.se k','6*ExplicitCurve.sg k+ExplicitCurve.sb k*ExplicitCurve.se k-4*ExplicitCurve.sc k*ExplicitCurve.sd k','4*ExplicitCurve.se k-ExplicitCurve.sb k*ExplicitCurve.sd k-6*ExplicitCurve.sc k','2*ExplicitCurve.sd k-3*ExplicitCurve.sb k','ExplicitCurve.sc k*w0 k-6','ExplicitCurve.sb k*w0 k+ExplicitCurve.sc k*w1 k','w0 k+ExplicitCurve.sb k*w1 k+ExplicitCurve.sc k*w2 k','w1 k+ExplicitCurve.sb k*w2 k+ExplicitCurve.sc k*k','ExplicitCurve.sb k^2-4*ExplicitCurve.sc k']
text='''/-
Copyright (c) 2026 Benjamin Stanley Frohman. Released under Apache 2.0 license.
Exact polynomial Bezout certificates for the actual section coefficients.
Generated by scripts/generate_residue_certificates.py; every identity below is
proved in Lean. The generator and SymPy are not part of the proof trust base.
No cohomology, cycle-class, ideal reducedness or resultant claim is made here.
-/
import Hodge.ExplicitResidueAlgebra

namespace Hodge.ExplicitResidueCertificates
open Polynomial
noncomputable section
set_option linter.unusedSimpArgs false
set_option linter.unnecessarySeqFocus false
set_option linter.unusedSectionVars false

'''
text+=f'def modulus : ℚ[X] := {poly(m.as_expr())}\n\n'
for n,p in base.items():text+=f'def {n} : ℚ[X] := {poly(p)}\n\n'
for n,ex in zip(names,exprs):text+=f'def {n}Poly : ℚ[X] := {ex}\n\n'
text+='section Evaluation\nvariable {K : Type*} [Field K] [CharZero K] [Algebra ℚ K]\n\n'
for n,ex in zip(names,scalar):text+=f'def {n} (k : K) : K := {ex}\n\n'
for n,old in zip(base,['sb','sc','sd','se','sg']):
 text+=f'''@[simp] theorem eval_{n} (k : K) : aeval k {n} = ExplicitCurve.{old} k := by
  simp [{n}, ExplicitCurve.{old}, map_div₀]

'''
for n,ex in zip(names,exprs):
 text+=f'''@[simp] theorem eval_{n} (k : K) : aeval k {n}Poly = {n} k := by
  simp [{n}Poly, {n}, map_add, map_sub, map_mul, map_ofNat]

'''
text+='end Evaluation\n\n'
allpolydefs=['modulus']+list(base)+[n+'Poly' for n in names]
for n,raw in zip(names,raws):
 raw=s.Poly(s.expand(raw),k);q,red=raw.div(m);a,bb,gcd=s.gcdex(red,m)
 assert gcd.as_expr()==1
 text+=f'def {n}Reduced : ℚ[X] := {poly(red.as_expr())}\n\n'
 text+=f'def {n}Quotient : ℚ[X] := {poly(q.as_expr())}\n\n'
 text+=f'def {n}Inverse : ℚ[X] := {poly(a.as_expr())}\n\n'
 text+=f'def {n}Bezout : ℚ[X] := {poly(bb.as_expr())}\n\n'
 text+=f'''theorem {n}_reduction : {n}Poly = {n}Reduced + {n}Quotient*modulus := by
  apply Polynomial.funext
  intro t
  norm_num [{', '.join(allpolydefs+[n+'Reduced',n+'Quotient'])}]
  <;> ring

theorem {n}_bezout : {n}Inverse*{n}Reduced + {n}Bezout*modulus = 1 := by
  apply Polynomial.funext
  intro t
  norm_num [modulus, {n}Inverse, {n}Reduced, {n}Bezout]
  <;> ring

'''
text+='''/-- This algebra lemma is applied only to explicit polynomial identities proved above. -/
theorem eval_ne_zero_of_certificate {K : Type*} [Field K] [CharZero K] [Algebra ℚ K]
    {p r q a b : ℚ[X]} (hred : p = r+q*modulus)
    (hbez : a*r+b*modulus=1) (k : K) (hm : aeval k modulus=0) :
    aeval k p ≠ 0 := by
  intro hp
  have hh := congrArg (aeval k) hred
  have hr : aeval k r = 0 := by
    simpa [map_add, map_mul, map_one, hm, hp] using hh.symm
  have hb := congrArg (aeval k) hbez
  simp [map_add, map_mul, map_one, hm, hr] at hb

section Nonvanishing
variable {K : Type*} [Field K] [CharZero K] [Algebra ℚ K]

'''
for n in names:
 text+=f'''/-- Actual section coefficient nonvanishing: only the original modulus-root hypothesis. -/
theorem {n}_ne_zero (k : K)
    (hm : k^24+66081312000*k^18-4811512860000*k^12+
      1167566400000*k^6+583200000=0) : {n} k ≠ 0 := by
  have hm' : aeval k modulus=0 := by simpa [modulus, map_ofNat, sub_eq_add_neg] using hm
  have h := eval_ne_zero_of_certificate {n}_reduction {n}_bezout k hm'
  simpa using h

'''
text+='end Nonvanishing\n\n/-- Nonvacuity: the actual modulus has degree 24. -/\ntheorem modulus_degree : modulus.degree = 24 := by\n  unfold modulus\n  compute_degree <;> norm_num <;> decide +kernel\n\n/-- An actual complex root exists; the nonvanishing statements are not merely\nuniversal statements over a field with no section roots. -/\ntheorem exists_complex_root : ∃ k : ℂ, aeval k modulus = 0 := by\n  exact IsAlgClosed.exists_aeval_eq_zero ℂ modulus (by rw [modulus_degree]; norm_num)\n\n/-- All eight section-coefficient formulas and the discriminant are nonzero at\nan actual complex section root. This is not a geometric cycle-class assertion. -/\ntheorem exists_complex_nonvanishing : ∃ k : ℂ,\n    k^24+66081312000*k^18-4811512860000*k^12+\n      1167566400000*k^6+583200000=0 ∧\n    w0 k ≠ 0 ∧ w1 k ≠ 0 ∧ w2 k ≠ 0 ∧ w3 k ≠ 0 ∧\n    u0 k ≠ 0 ∧ u1 k ≠ 0 ∧ u2 k ≠ 0 ∧ u3 k ≠ 0 ∧ disc k ≠ 0 := by\n  obtain ⟨k, hk⟩ := exists_complex_root\n  have hm : k^24+66081312000*k^18-4811512860000*k^12+\n      1167566400000*k^6+583200000=0 := by\n    simpa [modulus, map_ofNat, sub_eq_add_neg] using hk\n  exact ⟨k, hm, w0_ne_zero k hm, w1_ne_zero k hm, w2_ne_zero k hm,\n    w3_ne_zero k hm, u0_ne_zero k hm, u1_ne_zero k hm,\n    u2_ne_zero k hm, u3_ne_zero k hm, disc_ne_zero k hm⟩\n\nend\nend Hodge.ExplicitResidueCertificates\n'
(R/'Hodge/ExplicitResidueCertificates.lean').write_text(text)
